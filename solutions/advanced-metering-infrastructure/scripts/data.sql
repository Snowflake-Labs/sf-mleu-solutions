FROM (
  SELECT SERVICE_POINT_ID, PREMISE_TYPE, UTILITY_TERRITORY,
         ROW_NUMBER() OVER (ORDER BY SERVICE_POINT_ID) AS rn
  FROM SERVICE_POINT
) SP;

